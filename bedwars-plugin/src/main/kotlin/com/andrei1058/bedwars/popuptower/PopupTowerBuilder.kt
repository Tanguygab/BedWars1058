    fun build(loc: Location, originBlock: Block, color: TeamColor, player: Player, positions: Array<String>) {
        // Consume exactly one item from player's hand, preserving original behavior
        val plugin = BedWars.INSTANCE
        val item = plugin.versionSupport.getItemInHand(player)
        if (item.amount <= 0) {
            player.inventory.setItemInHand(null)
        } else item.amount -= 1

        var amount = 0
        plugin.repeat(0, 1) { task ->
            Sounds.playSoundArea("pop-up-tower-build", loc, 1.0f, 0.5f)

            (0..<2).forEach {
                if (positions.size + 1 == amount + 1 + it) {
                    task.cancel()
                    return@repeat
                }
                val position = positions[amount + it]
                val data = if ("ladder" in position) position.split("ladder")[1].toInt() else 0
                place(originBlock, position, color, player, "ladder" in position, data)
            }

            amount += 2
        }
    }

    fun handleTowerPlace(player: Player, block: Block) {
        val arena = BedWars.INSTANCE.arenaManager.getArena(player) ?: return

        // Centralized placement entrypoint for popup towers
        val loc = block.location

        // Pre-build height check: base Y + TOWER_HEIGHT must not exceed arena max build Y
        val maxY = arena.config.getInt(ConfigPath.ARENA_CONFIGURATION_MAX_BUILD_Y)
        if (loc.blockY + TOWER_HEIGHT > maxY) return // stop silently as requested; event already cancelled

        val col = arena.getTeam(player)!!.color
        build(loc, block, col, player, getLocations(player))
    }

    private fun getLocations(player: Player): Array<String> {
        var rotation = (player.location.yaw - 90.0f) % 360.0f
        while (rotation < 0) rotation += 360

        return when (rotation % 360) {
            in 45.0..<135.0 -> facingSouth
            in 225.0..<315.0 -> facingNorth
            in 135.0..<225.0 -> facingWest
            else -> facingEast // 0-45 or 315-360 -> EAST
        }
    }

    private fun place(block: Block, xyz: String, color: TeamColor, player: Player, ladder: Boolean, ladderData: Int) {
        val pos = xyz.split(", ")
        val x = pos[0].toInt()
        val y = pos[1].toInt()
        val z = pos[2].toInt()
        // Target location for the next placement
        val target = block.getRelative(x, y, z)
        if (target.type != Material.AIR) return

        // Reuse BreakPlace protection around spawns/shops/upgrades/generators
        val plugin = BedWars.INSTANCE
        val arena = plugin.arenaManager.getArena(player)!!
        if (BreakPlace.isProtectedLocation(arena, target.location)) return

        if (ladder) plugin.versionSupport.placeLadder(block, x, y, z, arena, ladderData)
        else plugin.versionSupport.placeTowerBlocks(block, arena, color, x, y, z)
    }
